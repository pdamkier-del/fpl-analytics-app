/* Browser-like navigation smoke for offline Model Explorer, using jsdom. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { JSDOM } = require('jsdom');
const html=fs.readFileSync('app/models.html','utf8');
const data=fs.readFileSync('app/model-tree-data.js','utf8');
const ui=fs.readFileSync('app/model-tree-ui.js','utf8');
const dom=new JSDOM(html,{url:'http://localhost:8765/models.html',runScripts:'outside-only'});
const {window}=dom;const d=window.document;
window.HTMLElement.prototype.scrollIntoView = function () {};
window.eval(data);
window.eval(ui);
const get=id=>d.querySelector(id);
const click=el=>{assert.ok(el,'missing click target');el.click();};
assert.equal(d.querySelectorAll('#model-roadmap [data-open-node]').length,5);
assert.equal(get('#model-detail h2').textContent,'Den samlede FPL-model');
click(get('#model-roadmap [data-open-node="mm"]'));
assert.ok(get('#model-detail h2').textContent.includes('Minutmodellen'));
assert.ok(get('#model-detail').textContent.includes('xMins'));
click(get('#model-detail [data-open-node="mm-mi"]'));
click(get('#model-detail [data-open-node="mm-mi-comp"]'));
assert.ok(get('#model-detail').textContent.includes('0,35'));
assert.equal(window.location.hash,'#model=mm-mi-comp');
click(get('#model-detail .model-breadcrumb [data-open-node="root"]'));
assert.equal(get('#model-detail h2').textContent,'Den samlede FPL-model');
const search=get('#model-tree-search');
search.value='autosub';search.dispatchEvent(new window.Event('input',{bubbles:true}));
assert.ok(!get('#model-search-results').hidden);
assert.ok(get('#model-search-results [data-open-node]'));
click(get('#model-search-results [data-open-node="chips-bb-auto"]'));
assert.ok(get('#model-detail h2').textContent.includes('Autosub'));
assert.ok(get('#model-detail').textContent.includes('E[autosub]'));
click(get('#collapse-model-tree'));
assert.ok(d.querySelectorAll('#model-nav-tree .model-tree-label').length < 15);
click(get('#expand-model-tree'));
assert.equal(d.querySelectorAll('#model-nav-tree .model-tree-label').length,window.FPL_MODEL_TREE.nodes.length);
window.location.hash='#model=chips-tc-future';
window.dispatchEvent(new window.HashChangeEvent('hashchange'));
assert.ok(get('#model-detail h2').textContent.includes('fremtid'));
assert.ok(get('#model-detail').textContent.includes('8,57'));
const source=get('#model-detail .source-link');
assert.ok(source.href.includes('/blob/fpl-model-complete-locked-20261009/'));
console.log('Model tree UI smoke: 5 branches, deep navigation, formulas, search, expansion and direct links passed');
